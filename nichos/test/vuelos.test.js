const assert = require('assert');
const v = require('../vuelos');
const now = new Date('2026-11-13T10:00:00Z');
const f = (dest, price, dep, extra = {}) => ({ origin: 'MUR', origin_airport: 'RMU', destination: dest, price, departure_at: dep, transfers: 0, airline: 'FR', link: `/search/RMU1512${dest}1?t=x`, ...extra });
const data = [f('LON', 40, '2026-12-15T07:00:00+01:00'), f('LON', 25, '2026-12-20T07:00:00+01:00'), f('BCN', 15, '2026-11-15T07:00:00+01:00'), f('BCN', 30, '2026-12-01T09:00:00+01:00'), f('PAR', 20, '2027-06-01T07:00:00+01:00')];
const best = v.bestByDestination(data, now);
assert.deepStrictEqual(best.map((b) => [b.route, b.price]).sort(), [['RMU-BCN', 30], ['RMU-LON', 25]], 'too soon / too far excluded, cheapest kept');
assert.strictEqual(v.median([10, 30, 20]), 20);
const hist = [60, 55, 70, 65, 58, 62].map((p, i) => ({ d: `2026-11-0${i + 1}`, p }));
const lon = best.find((b) => b.route === 'RMU-LON');
const ev = v.evaluate(lon, hist, {}, now);
assert.strictEqual(ev.reason, 'below-median'); assert.strictEqual(ev.median, 61); assert.strictEqual(ev.dropPct, 59);
assert.strictEqual(v.evaluate({ ...lon, price: 50 }, hist, {}, now), null, 'not cheap enough');
assert.strictEqual(v.evaluate({ ...lon, price: 50 }, hist.slice(0, 3), {}, now), null, 'few samples and not absolute');
assert.strictEqual(v.evaluate({ ...lon, price: 18 }, [], {}, now).reason, 'absolute');
assert.strictEqual(v.evaluate(lon, hist, { 'RMU-LON': { at: '2026-11-10T00:00:00Z', price: 26 } }, now), null, 'recently posted similar price');
assert.ok(v.evaluate(lon, hist, { 'RMU-LON': { at: '2026-11-10T00:00:00Z', price: 40 } }, now), 'reposts if 15% cheaper');
assert.strictEqual(v.buildLink('/search/RMU1512LON1?t=x', 'M123'), 'https://www.aviasales.com/search/RMU1512LON1?t=x&marker=M123');
assert.deepStrictEqual(v.monthsAhead(3, now), ['2026-11', '2026-12', '2027-01']);
const post = v.buildPost(lon, ev, 'Londres', 'M123');
assert.ok(post.includes('Murcia (Corvera) → Londres') && post.includes('25 €') && post.includes('59% más barato') && post.includes('Ryanair'));
console.log('Vuelos tests passed\n' + post.replace(/<[^>]+>/g, ''));
